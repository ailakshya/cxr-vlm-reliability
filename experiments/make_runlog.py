"""Write RUN_LOG.md: one row per queue job (when, how long, images, seconds per image, status), from queue.log + runs/.

  python make_runlog.py [out.md]        default: $CXR_ROOT/logs/RUN_LOG.md
"""
import json, os, re, sys
from datetime import datetime

ROOT = os.environ.get("CXR_ROOT", "/mnt/hdd/cxr_vlm")
OUT = sys.argv[1] if len(sys.argv) > 1 else f"{ROOT}/logs/RUN_LOG.md"

rows, start = [], {}
for line in open(f"{ROOT}/logs/queue.log"):
    m = re.match(r"(\S+) (START|DONE|FAILED) (.+)$", line.strip())
    if not m:
        continue
    t, ev, job = datetime.fromisoformat(m[1]), m[2], m[3]
    if ev == "START":
        start[job] = t
    elif job in start:
        rows.append((start.pop(job), t, ev, job))
rows += [(t, None, "RUNNING", j) for j, t in start.items()]   # ponytail: last START without an end = running


def run_stats(job):
    model, site, cond = job.split()[:3]
    p = f"{ROOT}/runs/{model}/{site}/{cond.replace(':', '_')}.jsonl"
    if not os.path.exists(p):
        return "", ""
    secs = [json.loads(l)["sec"] for l in open(p)]
    return str(len(secs)), f"{sum(secs) / len(secs):.1f}" if secs else ""


out = ["# Run log", "", "Generated by `experiments/make_runlog.py` from `logs/queue.log`. Inference only; no model is trained.", "",
       "| Started | Duration (min) | Job (model site cond n k kloc) | Status | Images in run file | s/img |",
       "|---|---|---|---|---|---|"]
for t0, t1, ev, job in rows:
    n, s = run_stats(job)
    dur = f"{(t1 - t0).total_seconds() / 60:.0f}" if t1 else ""
    out.append(f"| {t0:%Y-%m-%d %H:%M} | {dur} | `{job}` | {ev} | {n} | {s} |")
open(OUT, "w").write("\n".join(out) + "\n")
print("wrote", OUT, len(rows), "jobs")
